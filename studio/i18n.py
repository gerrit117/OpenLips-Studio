def language():
    global _language
    if _language is None:
        default = 'de' if QLocale.system().language() == QLocale.Language.German else 'en'
        value = QSettings('OpenLips', 'OpenLips Studio').value('ui/language', default)
        _language = value if value in ('en', 'de') else 'en'
    return _language


def set_language(value, persist=True):
    global _language
    if value not in ('en', 'de'):
        raise ValueError('Supported UI languages: en, de')
    _language = value
    if persist:
        QSettings('OpenLips', 'OpenLips Studio').setValue('ui/language', value)


def tr(message, **values):
    pair = CATALOG.get(message)
    text = pair[language() == 'de'] if pair else message
    return text.format(**values) if values else text
